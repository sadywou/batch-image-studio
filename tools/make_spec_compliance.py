def load_results():
    """Читает результаты замеров из build/*.json.

    Returns:
        Словарь с показателями назначения и приёмочных испытаний.
    """
    metrics = {}
    path = BUILD / "spec_metrics.json"
    if path.exists():
        for item in json.loads(path.read_text(encoding="utf-8")):
            metrics[item["metric"]] = item
    acceptance = []
    path = BUILD / "acceptance.json"
    if path.exists():
        acceptance = json.loads(path.read_text(encoding="utf-8"))
    return metrics, acceptance


