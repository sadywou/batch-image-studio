def setup(document: Document) -> None:
    """Настраивает базовый стиль документа под требования отчёта."""
    style = document.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    style.paragraph_format.line_spacing = 1.5
    style.paragraph_format.first_line_indent = Cm(1.25)
    style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    for name in ("Heading 1", "Heading 2", "Heading 3", "List Bullet"):
        try:
            head = document.styles[name]
        except KeyError:
            continue
        head.font.name = "Times New Roman"


def text(document: Document, value: str, *, bold=False, italic=False,
         align=None, indent=True, space_after=6) -> None:
    """Добавляет абзац основного текста."""
    paragraph = document.add_paragraph()
    run = paragraph.add_run(value)
    run.bold = bold
    run.italic = italic
    if align is not None:
        paragraph.alignment = align
    if not indent:
        paragraph.paragraph_format.first_line_indent = Cm(0)
    paragraph.paragraph_format.space_after = Pt(space_after)
    return paragraph


def heading(document: Document, value: str, level: int = 2) -> None:
    """Добавляет заголовок без отступа первой строки."""
    paragraph = document.add_heading(level=level)
    run = paragraph.add_run(value)
    run.font.name = "Times New Roman"
    paragraph.paragraph_format.first_line_indent = Cm(0)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
    return paragraph


def bullets(document: Document, items) -> None:
    """Добавляет маркированный список."""
    for item in items:
        paragraph = document.add_paragraph(style="List Bullet")
        run = paragraph.add_run(item)
        run.font.name = "Times New Roman"
        run.font.size = Pt(14)
        paragraph.paragraph_format.first_line_indent = Cm(0)
        paragraph.paragraph_format.space_after = Pt(2)


def caption(document: Document, value: str) -> None:
    """Добавляет подпись к рисунку или таблице по центру."""
    paragraph = document.add_paragraph()
    run = paragraph.add_run(value)
    run.font.name = "Times New Roman"
    run.font.size = Pt(14)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.first_line_indent = Cm(0)
    paragraph.paragraph_format.space_after = Pt(12)


def table(document: Document, header, rows, widths=None):
    """Добавляет таблицу с заголовком и рамкой."""
    created = document.add_table(rows=1, cols=len(header))
    created.style = "Table Grid"
    created.alignment = WD_TABLE_ALIGNMENT.CENTER
    for index, value in enumerate(header):
        cell = created.rows[0].cells[index]
        cell.text = ""
        run = cell.paragraphs[0].add_run(str(value))
        run.bold = True
        run.font.size = Pt(12)
        run.font.name = "Times New Roman"
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        cell.paragraphs[0].paragraph_format.first_line_indent = Cm(0)
    for row in rows:
        cells = created.add_row().cells
        for index, value in enumerate(row):
            cells[index].text = ""
            run = cells[index].paragraphs[0].add_run(str(value))
            run.font.size = Pt(12)
            run.font.name = "Times New Roman"
            cells[index].paragraphs[0].paragraph_format.first_line_indent = Cm(0)
    if widths:
        for row in created.rows:
            for index, width in enumerate(widths):
                row.cells[index].width = Cm(width)
    return created


def figure(document: Document, filename: str, title: str, width_cm=16.0) -> bool:
    """Вставляет рисунок из папки screenshots."""
    path = SHOTS / filename
    if not path.exists():
        return False
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.first_line_indent = Cm(0)
    paragraph.add_run().add_picture(str(path), width=Cm(width_cm))
    caption(document, title)
    return True


