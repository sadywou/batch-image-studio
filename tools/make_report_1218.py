def count_tests() -> int:
    """Подсчитывает собранные автотесты.

    Returns:
        Количество тестов, собранных pytest.
    """
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
         "--collect-only"],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        cwd=ROOT, check=False,
    )
    for line in result.stdout.splitlines():
        if "tests collected" in line or "test collected" in line:
            return int(line.split()[0])
    return 0


def read_coverage() -> tuple:
    """Измеряет покрытие кода и читает результат из coverage.xml.

    Покрытие пересчитывается при каждой сборке отчёта: без этого в
    документ попали бы числа, соответствующие более ранней версии
    программы.

    Returns:
        Пара ``(процент покрытия, процент покрытия по ветвлениям)``.
    """
    subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
         "--cov=app", "--cov-report=xml"],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        cwd=ROOT, check=False,
    )
    path = ROOT / "coverage.xml"
    if not path.exists():
        return (0.0, 0.0)
    root = ET.parse(path).getroot()
    percent = float(root.get("line-rate", 0)) * 100
    branch = float(root.get("branch-rate", 0)) * 100
    return (round(percent, 1), round(branch, 1))


def exe_size() -> tuple:
    """Возвращает размер готового исполняемого файла.

    Returns:
        Пара ``(размер в мегабайтах, размер в байтах)``.
    """
    path = ROOT / "dist" / "BatchImageStudio.exe"
    if not path.exists():
        return (0.0, 0)
    return (round(path.stat().st_size / 1024 / 1024, 1), path.stat().st_size)


def load_json(name: str):
    """Читает JSON-отчёт из папки build.

    Args:
        name: Имя файла без расширения.

    Returns:
        Разобранные данные или пустой список.
    """
    path = BUILD / f"{name}.json"
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8"))


def count_tests_by_file() -> dict:
    """Подсчитывает число тестов в каждом файле набора.

    Returns:
        Словарь ``{имя файла: количество тестов}``.
    """
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
         "--collect-only"],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        cwd=ROOT, check=False,
    )
    counts = {}
    for line in result.stdout.splitlines():
        if line.startswith("tests/") and "::" in line:
            name = Path(line.split("::")[0]).stem
            counts[name] = counts.get(name, 0) + 1
    return counts


