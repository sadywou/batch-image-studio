def perf_number(metrics, needle: str, default: str = "—") -> str:
    """Находит значение замера по фрагменту названия.

    Args:
        metrics: Список результатов замеров.
        needle: Фрагмент названия показателя.
        default: Значение при отсутствии замера.

    Returns:
        Строковое представление значения с единицей измерения.
    """
    for item in metrics:
        if needle.lower() in str(item.get("metric", "")).lower():
            return f"{item['value']} {item.get('unit', '')}".strip()
    return default


