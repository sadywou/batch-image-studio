"""Записывает текст сообщения коммита в файл без BOM.

Скрипт нужен потому, что PowerShell в Windows PowerShell 5 записывает
файл в кодировке UTF-8 с меткой порядка байтов, и она попадает
в первое слово сообщения коммита.

Запуск:  python tools/write_commit_message.py
"""
import sys
from pathlib import Path

MESSAGE = """Приведение к требованиям ТЗ и обновление интерфейса

Сверка программы с техническим заданием выявила 11 расхождений,
все устранены. Основные изменения:

- пять режимов изменения размера вместо двух полей в пикселях;
- девять позиций водяного знака и графический знак из файла PNG;
- настройка размера и цвета водяного знака;
- текстовый журнал выполнения, закреплённый внизу карточки;
- меню "Помощь" со сведениями о программе;
- схема базы приведена к пункту 4.3.2 задания, добавлена миграция;
- статусы журнала SUCCESS и ERROR вместо русских значений;
- управление зависимостями через Poetry, создан poetry.lock;
- собственные выпадающие списки и образец цвета вместо стандартных;
- сборка BatchImageStudio.exe по наименованию из задания.

Тесты: 234 проходят, покрытие кода 86 % по строкам,
замечаний статического анализатора нет.
"""


def main() -> int:
    """Записывает сообщение коммита в переданный или временный файл."""
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("COMMIT_EDITMSG.txt")
    target.write_text(MESSAGE, encoding="utf-8", newline="\n")
    print("сообщение записано:", target, "| символов:", len(MESSAGE))
    print("первые байты:", target.read_bytes()[:4])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())