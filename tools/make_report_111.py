def project_facts() -> dict:
    """Собирает факты о текущем состоянии проекта из репозитория.

    Returns:
        Словарь с составом модулей, схемой базы и перечнем форматов.
    """
    sys.path.insert(0, str(ROOT))
    from app.database import DatabaseManager
    from app.ui import SUPPORTED_EXTENSIONS

    modules = {}
    for path in sorted((ROOT / "app").glob("*.py")):
        lines = len(path.read_text(encoding="utf-8").splitlines())
        modules[path.name] = lines
    runner = ROOT / "run_app.py"
    if runner.exists():
        modules["run_app.py"] = len(runner.read_text(encoding="utf-8").splitlines())

    work = Path(tempfile.mkdtemp())
    manager = DatabaseManager(str(work / "report.db"))
    schema = {}
    for name in ("tbl_formats", "tbl_presets", "tbl_watermarks",
                 "tbl_history_sessions", "tbl_processed_files"):
        rows = manager.connection.execute(f"PRAGMA table_info({name})").fetchall()
        schema[name] = [row[1] for row in rows]
    manager.close()
    return {"modules": modules, "schema": schema,
            "formats": SUPPORTED_EXTENSIONS}


