"""Обновляет описание интерфейса в functionality.rst.

Ширина рамок таблиц RST задаётся пробелами, поэтому новые таблицы
собираются функцией :func:`table`, а не набираются вручную: при
ручном наборе ширина «едет» на символ, и docutils отвергает весь
документ.

Запуск:  python tools/patch_functionality_rst.py
"""
import sys
from pathlib import Path

TARGET = (Path(__file__).resolve().parent.parent / "docs" / "source"
          / "functionality.rst")

#: Разделитель столбцов таблиц этого раздела.
COLUMNS = 28, 49

DRAG_HINT = """
Пока файлы перетаскиваются над окном, рамка карточки под курсором
пульсирует акцентным цветом, а заголовок карточки очереди подсказывает,
что файлы нужно отпустить. Подсветка не накрывает содержимое карточки,
поэтому очередь и форма остаются видимыми.
"""

PRESET_TABLE = """\
{rule}
Элемент                       Назначение
Поле «ИМЯ ПРОФИЛЯ»            Имя нового или выбранного профиля
«Сохранить»                   Создание профиля или обновление существующего
«Удалить»                     Удаление профиля, указанного в поле
Крестик на карточке           Удаление профиля напрямую
Клик по карточке              Применение профиля к форме
{rule}"""

NEW_SECTIONS = """
Профили настроек
~~~~~~~~~~~~~~~~

Профили хранятся в базе и показываются карточками в отдельной панели
«Профили» между очередью и формой. Каждая карточка содержит название
и краткий состав профиля: формат, размер, качество и наличие водяного
знака. Активный профиль подсвечен рамкой.

{preset_table}

Клавиша ``Enter`` в поле имени сохраняет профиль. Удаление требует
подтверждения, а пустое имя приводит только к предупреждению.

Отчёт об обработке
~~~~~~~~~~~~~~~~~~

Журнал сессий и обработанных файлов выгружается в CSV-кнопкой
«Экспорт отчёта в CSV» и пунктом меню «Файл». Файл содержит русские
названия столбцов, разделитель ``;`` и кодировку UTF-8 с меткой
порядка байтов, поэтому открывается в Excel и LibreOffice Calc без
подготовки. Экономия размера в процентах считается только для
успешно обработанных файлов: у ошибочных результата нет, и нулевой
размер дал бы ложное сокращение в сто процентов.
"""


def _rule() -> str:
    """Возвращает рамку той же ширины, что и у соседних таблиц.

    Returns:
        Строка из знаков равенства и двух пробелов между столбцами.
    """
    first, second = COLUMNS
    return "=" * first + "  " + "=" * second


def main() -> int:
    """Вносит правки в описание очереди, профилей и отчёта."""
    text = TARGET.read_text(encoding="utf-8")
    rule = _rule()
    replacements = [
        (
            "Карточка файла                Миниатюра, имя, размер, статус, "
            "кнопка удаления",
            "Карточка файла                Миниатюра, имя, размер, бейдж "
            "экономии, статус, кнопка удаления",
        ),
        (
            "обработка, очередь заблокирована: добавление и удаление "
            "недоступны.\n",
            "обработка, очередь заблокирована: добавление и удаление "
            "недоступны.\n" + DRAG_HINT,
        ),
        (
            "«Сохранить»                   Сохранение настроек под именем "
            "в базу\n",
            NEW_SECTIONS.format(preset_table=PRESET_TABLE.format(rule=rule)),
        ),
    ]
    for old, new in replacements:
        if old in text:
            text = text.replace(old, new, 1)
            print("заменено:", old.splitlines()[0][:56])
        else:
            print("уже актуально:", old.splitlines()[0][:56])

    # Нижняя рамка таблицы настроек осталась в файле, но переехала вниз
    # вместе с новыми разделами. Возвращаем её на место, иначе таблица
    # остаётся незакрытой и docutils считает её повреждённой.
    orphan = "размер дал бы ложное сокращение в сто процентов.\n" + rule + "\n"
    if orphan in text:
        text = text.replace(orphan, "размер дал бы ложное сокращение в сто процентов.\n", 1)
        print("убрана осиротевшая рамка")
    closing = "Папка сохранения              Куда записывать готовые файлы\n"
    if closing + rule + "\n" not in text:
        text = text.replace(closing, closing + rule + "\n", 1)
        print("возвращена нижняя рамка таблицы настроек")

    TARGET.write_text(text, encoding="utf-8")
    print("функциональность.rst обновлена")
    return 0


if __name__ == "__main__":
    sys.exit(main())